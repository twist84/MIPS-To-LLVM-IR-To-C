#include "ee_gs.h"

#include <array>
#include <cstdint>
#include <cstdio>
#include <vector>

namespace
{
int fail(const char* reason)
{
    std::fprintf(stderr, "EE GS PSMT4: %s\n", reason);
    return 1;
}

uint64_t bitblt(uint32_t base, uint32_t width, uint32_t psm)
{
    return (static_cast<uint64_t>(base) << 32u) |
        (static_cast<uint64_t>(width) << 48u) |
        (static_cast<uint64_t>(psm) << 56u);
}

uint64_t trxpos(uint32_t x, uint32_t y)
{
    return (static_cast<uint64_t>(x) << 32u) |
        (static_cast<uint64_t>(y) << 48u);
}

uint64_t trxreg(uint32_t width, uint32_t height)
{
    return width | (static_cast<uint64_t>(height) << 32u);
}

bool reg(ee::c_ee_gs_state& gs, uint32_t index, uint64_t value)
{
    ee::s_ee_gif_event event{};
    event.m_type = ee::e_ee_gif_event_type::packed;
    event.m_register = 0xeu;
    event.m_word0 = value;
    event.m_word1 = index;
    const std::array<uint8_t, 16> dummy{};
    return gs.consume(&event, 1u, dummy.data(), 1u);
}

bool image(ee::c_ee_gs_state& gs, const uint8_t* data, uint32_t qwc)
{
    ee::s_ee_gif_event event{};
    event.m_type = ee::e_ee_gif_event_type::image;
    event.m_qwc = qwc;
    return gs.consume(&event, 1u, data, qwc);
}

bool read8(const ee::c_ee_gs_state& gs, uint32_t offset, uint8_t expected)
{
    uint8_t actual = 0u;
    return gs.read_vram8(offset, actual) && actual == expected;
}

bool read32(const ee::c_ee_gs_state& gs, uint32_t offset, uint32_t expected)
{
    uint32_t actual = 0u;
    return gs.read_vram32(offset, actual) && actual == expected;
}

void set_nibble(uint8_t* data, uint32_t index, uint8_t value)
{
    const uint32_t offset = index / 2u;
    const uint8_t shift = static_cast<uint8_t>((index & 1u) * 4u);
    const uint8_t mask = static_cast<uint8_t>(0x0fu << shift);
    data[offset] = static_cast<uint8_t>(
        (data[offset] & static_cast<uint8_t>(~mask)) |
        static_cast<uint8_t>((value & 0x0fu) << shift)
    );
}

void set32(uint8_t* data, uint32_t value)
{
    for (uint32_t i = 0u; i < 4u; ++i)
    {
        data[i] = static_cast<uint8_t>(value >> (i * 8u));
    }
}
} // namespace

int main()
{
    ee::c_ee_gs_state gs;
    constexpr uint32_t k_bp = 0x140u;
    constexpr uint32_t k_base = k_bp * 256u;

    // Reserved destination format 0x03 has no supported swizzle.
    // Unsupported transfer setup must not commit TRXDIR.
    if (!reg(gs, 0x50u, bitblt(k_bp, 4u, 0x03u)) ||
        !reg(gs, 0x51u, trxpos(0u, 127u)) ||
        !reg(gs, 0x52u, trxreg(129u, 2u)) ||
        reg(gs, 0x53u, 0u) ||
        gs.was_written(0x53u) ||
        gs.state().m_transfer_started)
    {
        return fail("unsupported reserved PSM 0x03 configuration was accepted");
    }

    // The 129x2 rectangle at y=127 crosses X=128 and Y=128 page
    // boundaries; DBW=4 means two pages per row. Packed 4-bit pixels
    // continue across odd-width rows without an intervening pad nibble.
    // The byte offsets are fixed fixtures from the reference's block
    // and nibble tables (and are not generated by the code under test).
    std::vector<uint8_t> pixels(9u * 16u, 0xeeu);
    for (uint32_t i = 0u; i < 258u; ++i)
    {
        set_nibble(
            pixels.data(), i, static_cast<uint8_t>(1u + i % 15u)
        );
    }

    if (!reg(gs, 0x50u, bitblt(k_bp, 4u, 0x14u)) ||
        !reg(gs, 0x53u, 0u) ||
        !gs.state().m_transfer_started ||
        !image(gs, pixels.data(), 4u) ||
        gs.state().m_transfer_pixels_written != 128u ||
        gs.state().m_image_qwc != 4u ||
        !read8(gs, k_base + 5576u, 0x10u) ||
        !read8(gs, k_base + 5580u, 0x20u) ||
        !read8(gs, k_base + 5577u, 0x90u) ||
        !read8(gs, k_base + 5578u, 0x20u) ||
        !read8(gs, k_base + 6088u, 0x30u) ||
        !read8(gs, k_base + 7624u, 0x50u) ||
        !read8(gs, k_base + 8191u, 0x80u) ||
        !read8(gs, k_base + 8192u + 5576u, 0u) ||
        !read8(gs, k_base + 16384u, 0u))
    {
        return fail("first IMAGE batch or PSMT4 swizzle/nibble lanes");
    }

    // First pixel of the second IMAGE is x=128,y=127 (low source
    // nibble); the next is x=0,y=128 (high source nibble). They must
    // land on different pages, even though they share a source byte.
    if (!image(gs, pixels.data() + 4u * 16u, 5u) ||
        gs.state().m_transfer_pixels_written != 258u ||
        gs.state().m_transfer_pending_size != 0u ||
        gs.state().m_image_qwc != 9u ||
        !read8(gs, k_base + 8192u + 5576u, 0x90u) ||
        !read8(gs, k_base + 16384u, 0x0au) ||
        !read8(gs, k_base + 16384u + 4u, 0x0bu) ||
        !read8(gs, k_base + 16384u + 1u, 0x03u) ||
        !read8(gs, k_base + 16384u + 2u, 0x0bu) ||
        !read8(gs, k_base + 16384u + 512u, 0x0cu) ||
        !read8(gs, k_base + 16384u + 2048u, 0x0eu) ||
        !read8(gs, k_base + 24576u, 0x03u) ||
        !read8(gs, k_base + 24576u + 4u, 0u))
    {
        return fail("cross-page DMA, odd row width or padding");
    }

    // A late unsupported register must roll back every preceding
    // staged nibble write as well as the raster pixel cursor.
    if (!reg(gs, 0x53u, 0u))
    {
        return fail("unable to restart PSMT4 transfer");
    }
    std::array<uint8_t, 32> retry{};
    retry.fill(0xabu);
    ee::s_ee_gif_event events[2]{};
    events[0].m_type = ee::e_ee_gif_event_type::image;
    events[0].m_qwc = 1u;
    events[1].m_type = ee::e_ee_gif_event_type::packed;
    events[1].m_register = 0xeu;
    events[1].m_byte_offset = 16u;
    events[1].m_word1 = 0x61u; // unsupported FINISH
    if (gs.consume(events, 2u, retry.data(), 2u) ||
        gs.state().m_transfer_pixels_written != 0u ||
        !read8(gs, k_base + 5576u, 0x10u) ||
        !image(gs, retry.data(), 1u) ||
        gs.state().m_transfer_pixels_written != 32u ||
        !read8(gs, k_base + 5576u, 0xb0u))
    {
        return fail("invalid event changed VRAM nibbles or transfer cursor");
    }

    // PSMT4 must preserve the neighboring nibble AND the other three
    // bytes in a 32-bit word. x=0,y=0 owns byte 0's low nibble;
    // x=4,y=2 owns byte 0's high nibble.
    gs.reset();
    constexpr uint32_t k_half_base = 0x300u * 256u;
    std::array<uint8_t, 16> seed{};
    std::array<uint8_t, 16> low{};
    std::array<uint8_t, 16> high{};
    set32(seed.data(), 0x12345678u);
    set_nibble(low.data(), 0u, 0xdu);
    set_nibble(high.data(), 0u, 0xau);
    if (!reg(gs, 0x50u, bitblt(0x300u, 1u, 0u)) ||
        !reg(gs, 0x51u, trxpos(0u, 0u)) ||
        !reg(gs, 0x52u, trxreg(1u, 1u)) ||
        !reg(gs, 0x53u, 0u) ||
        !image(gs, seed.data(), 1u) ||
        !reg(gs, 0x50u, bitblt(0x300u, 1u, 0x14u)) ||
        !reg(gs, 0x53u, 0u) ||
        !image(gs, low.data(), 1u) ||
        !read32(gs, k_half_base, 0x1234567du) ||
        !reg(gs, 0x51u, trxpos(4u, 2u)) ||
        !reg(gs, 0x53u, 0u) ||
        !image(gs, high.data(), 1u) ||
        !read32(gs, k_half_base, 0x123456adu))
    {
        return fail("PSMT4 nibble commit overwrote neighbor bits");
    }

    // Also stage both opposing nibbles of one VRAM byte in a single
    // IMAGE event to test ordered commit and no lost updates.
    gs.reset();
    std::array<uint8_t, 16> mixed{};
    set_nibble(mixed.data(), 0u, 3u);  // (x=0, y=0), low
    set_nibble(mixed.data(), 14u, 9u); // (x=4, y=2), high
    if (!reg(gs, 0x50u, bitblt(0x300u, 1u, 0x14u)) ||
        !reg(gs, 0x51u, trxpos(0u, 0u)) ||
        !reg(gs, 0x52u, trxreg(5u, 3u)) ||
        !reg(gs, 0x53u, 0u) ||
        !image(gs, mixed.data(), 1u) ||
        !read8(gs, k_half_base, 0x93u) ||
        gs.state().m_transfer_pixels_written != 15u)
    {
        return fail("same-batch high and low nibble writes collided");
    }

    // Small DBW values use a minimum one-page stride. DBW=3 must
    // truncate to one 128-pixel-wide page (not round up to two).
    gs.reset();
    std::array<uint8_t, 16> one{};
    one[0] = 0x0bu;
    if (!reg(gs, 0x50u, bitblt(0x90u, 3u, 0x14u)) ||
        !reg(gs, 0x51u, trxpos(0u, 128u)) ||
        !reg(gs, 0x52u, trxreg(1u, 1u)) ||
        !reg(gs, 0x53u, 0u) ||
        !image(gs, one.data(), 1u) ||
        !read8(gs, 0x90u * 256u + 8192u, 0x0bu) ||
        !read8(gs, 0x90u * 256u + 16384u, 0u))
    {
        return fail("PSMT4 128-pixel page-row stride");
    }

    // The final 256-byte base block and the x=32 block wrap to
    // 256 bytes into the 4 MiB GS VRAM allocation.
    gs.reset();
    one[0] = 0x0cu;
    if (!reg(gs, 0x50u, bitblt(0x3fffu, 2u, 0x14u)) ||
        !reg(gs, 0x51u, trxpos(32u, 0u)) ||
        !reg(gs, 0x52u, trxreg(1u, 1u)) ||
        !reg(gs, 0x53u, 0u) ||
        !image(gs, one.data(), 1u) ||
        !read8(gs, 256u, 0x0cu) ||
        !read8(gs, 0x3fffu * 256u, 0u))
    {
        return fail("PSMT4 4 MiB GS VRAM wrapping");
    }

    // Destination pixel coordinates wrap at 11 bits before swizzling.
    gs.reset();
    one[0] = 0x21u;
    if (!reg(gs, 0x50u, bitblt(0x80u, 2u, 0x14u)) ||
        !reg(gs, 0x51u, trxpos(2047u, 0u)) ||
        !reg(gs, 0x52u, trxreg(2u, 1u)) ||
        !reg(gs, 0x53u, 0u) ||
        !image(gs, one.data(), 1u) ||
        !read8(gs, 0x80u * 256u + 15u * 8192u + 2615u, 0x01u) ||
        !read8(gs, 0x80u * 256u, 0x02u))
    {
        return fail("PSMT4 destination-coordinate wrapping");
    }

    uint8_t unused = 0u;
    if (gs.read_vram8(
            static_cast<uint32_t>(ee::c_ee_gs_state::k_vram_bytes),
            unused))
    {
        return fail("out-of-range byte read was accepted");
    }

    gs.reset();
    if (!read8(gs, 0x80u * 256u, 0u) ||
        gs.state().m_transfer_started ||
        gs.state().m_transfer_pixels_written != 0u ||
        gs.state().m_image_qwc != 0u)
    {
        return fail("GS reset did not clear PSMT4 VRAM and transfer state");
    }

    std::puts("GS PSMT4 swizzle, nibble preservation, DMA, rollback: PASS");
    return 0;
}
